"""Backing up the two things that would hurt to lose: the database, and the CV.

**One implementation, three entry points.** The CLI, the scheduled task and the
dashboard button all land here. The alternative — a PowerShell script on Windows,
a shell script on Linux, and something else again behind the API — is three
copies of the same rules, and the copies drift. When they drift, what drifts is
the *verification*, so the day you find out is the day you need the backup.

Two formats on purpose:

* ``pg_dump -Fc`` — compressed, restorable table-by-table with ``pg_restore``
  rather than all-or-nothing. Needs a compatible Postgres to read.
* the Master CV as JSON — readable by a human on any machine with no tooling at
  all, and the one artefact that cannot be regenerated by crawling again.

Two formats, two failure modes, so one bad assumption cannot take both.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

from jobpilot.config import get_config, get_secrets

#: Files this module writes, and therefore the only ones it will prune. A glob
#: broad enough to match something a user put in the directory by hand is a glob
#: that will eventually delete it.
DUMP_GLOB = "jobpilot-*.dump"
CV_GLOB = "cv-*.json"


class BackupError(RuntimeError):
    """The backup could not be produced, verified, or uploaded."""


@dataclass
class BackupFile:
    name: str
    size: int
    created: datetime
    kind: str  # "database" | "cv"


@dataclass
class BackupResult:
    dump: Path
    cv: Path
    size: int
    mirrored_to: str | None = None
    pruned: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


def libpq_url(database_url: str) -> str:
    """SQLAlchemy URL -> the form ``pg_dump`` accepts.

    ``postgresql+psycopg://`` is a SQLAlchemy dialect string; libpq rejects it
    with "invalid URI scheme", which reads like a malformed URL rather than a
    driver suffix nobody outside SQLAlchemy has heard of.
    """
    return re.sub(r"^postgresql\+\w+:", "postgresql:", database_url)


def find_pg_dump() -> str:
    """Locate ``pg_dump``, or raise saying so.

    Searched rather than assumed: on Windows it is not on PATH by default, and
    the directory carries the major version, which changes under you.
    """
    found = shutil.which("pg_dump")
    if found:
        return found
    candidates = sorted(
        Path("C:/Program Files/PostgreSQL").glob("*/bin/pg_dump.exe"), reverse=True
    )
    if candidates:
        return str(candidates[0])
    raise BackupError(
        "pg_dump not found. Install the PostgreSQL client tools, or add them to PATH."
    )


def list_backups(directory: Path | str | None = None) -> list[BackupFile]:
    """Everything in the backup directory, newest first."""
    directory = Path(directory or get_config().backup.dir).expanduser()
    if not directory.is_dir():
        return []

    out = []
    for pattern, kind in ((DUMP_GLOB, "database"), (CV_GLOB, "cv")):
        for path in directory.glob(pattern):
            stat = path.stat()
            out.append(
                BackupFile(
                    name=path.name,
                    size=stat.st_size,
                    created=datetime.fromtimestamp(stat.st_mtime, tz=timezone.utc),
                    kind=kind,
                )
            )
    return sorted(out, key=lambda f: f.created, reverse=True)


def _prune(directory: Path, keep_days: int, keep_last: int = 0) -> list[str]:
    """Delete old backups by age *and* by count, whichever bites first.

    Age alone leaves a hole: pressing the dashboard button five times in an
    afternoon writes ten files all comfortably inside the age window, so nothing
    is pruned and the directory grows forever. Count alone is no good either —
    one backup a month would keep the last fourteen for over a year.

    Each kind is counted separately, so a run that failed halfway (a dump with
    no CV beside it) cannot push the other kind out of the window.
    """
    removed: list[str] = []
    cutoff = (
        datetime.now(tz=timezone.utc).timestamp() - keep_days * 86400 if keep_days > 0 else None
    )

    for pattern in (DUMP_GLOB, CV_GLOB):
        files = sorted(directory.glob(pattern), key=lambda p: p.stat().st_mtime, reverse=True)
        for index, path in enumerate(files):
            too_old = cutoff is not None and path.stat().st_mtime < cutoff
            too_many = keep_last > 0 and index >= keep_last
            if too_old or too_many:
                path.unlink()
                removed.append(path.name)
    return removed


def _mirror(dump: Path, cv: Path, remote: str, keep_days: int, notes: list[str]) -> bool:
    """Copy verified backups to an rclone remote. False if rclone is missing.

    rclone rather than a synced folder (Google Drive for Desktop and the like):
    a synced folder propagates the local prune to the cloud within seconds, which
    makes the remote a mirror of this machine's mistakes instead of an
    independent copy of its data. Here the remote keeps its own, longer retention.
    """
    exe = shutil.which("rclone")
    if not exe:
        notes.append(f"rclone not on PATH - nothing uploaded to {remote}")
        return False

    for path in (dump, cv):
        proc = subprocess.run(
            [exe, "copy", str(path), remote, "--no-traverse"],
            capture_output=True,
            text=True,
            timeout=600,
        )
        if proc.returncode != 0:
            raise BackupError(f"rclone upload of {path.name} failed: {proc.stderr[-400:]}")

    # Confirm rather than trust the exit code: an upload to a misspelled remote
    # path can succeed into a directory nobody will look in.
    probe = subprocess.run(
        [exe, "lsf", remote], capture_output=True, text=True, timeout=120
    )
    if probe.returncode != 0 or dump.name not in probe.stdout:
        raise BackupError(
            f"rclone reported success but {dump.name} is not listed in {remote}"
        )

    if keep_days > 0:
        # Checked, because a silent failure here means the remote grows without
        # bound while every backup still reports success — the shape of problem
        # you find out about from a quota email months later. Not fatal though:
        # the copy is already uploaded, which is the part that matters.
        pruned = subprocess.run(
            [exe, "delete", remote, "--min-age", f"{keep_days}d"],
            capture_output=True,
            text=True,
            timeout=600,
        )
        if pruned.returncode != 0:
            notes.append(f"remote retention failed on {remote}: {pruned.stderr[-200:].strip()}")
    return True


def run_backup(
    directory: Path | str | None = None,
    *,
    keep_days: int | None = None,
    keep_last: int | None = None,
    remote: str | None = None,
    remote_keep_days: int | None = None,
    progress=None,
) -> BackupResult:
    """Dump the database and export the CV. Raises ``BackupError`` on any doubt.

    ``progress`` is the queue's callback when this runs as a task; ignored
    otherwise, so the CLI and the API share one code path.
    """
    cfg = get_config().backup
    directory = Path(directory or cfg.dir).expanduser()
    keep_days = cfg.keep_days if keep_days is None else keep_days
    keep_last = cfg.keep_last if keep_last is None else keep_last
    remote = cfg.remote if remote is None else remote
    remote_keep_days = cfg.remote_keep_days if remote_keep_days is None else remote_keep_days

    def step(message: str) -> None:
        if progress:
            progress(message)

    directory.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    dump = directory / f"jobpilot-{stamp}.dump"
    cv_out = directory / f"cv-{stamp}.json"
    notes: list[str] = []

    step("dumping the database (this is the slow part)")
    pg_dump = find_pg_dump()
    url = libpq_url(get_secrets().database_url)
    # ``TimeoutExpired`` stores the whole argv and renders it in ``str()``, so
    # letting it propagate would put the DSN — password included — into the Run
    # row's error field, into the database, and onto the dashboard.
    #
    # The raise happens *outside* the except block on purpose. ``from None``
    # only suppresses how the chain is *displayed*; ``__context__`` still points
    # at the original, and a traceback renders the whole chain. Leaving the
    # block first is what actually drops it.
    timed_out: float | None = None
    try:
        proc = subprocess.run(
            [pg_dump, "-Fc", url, "-f", str(dump)],
            capture_output=True,
            text=True,
            timeout=1800,
        )
    except subprocess.TimeoutExpired as exc:
        timed_out = exc.timeout
    if timed_out is not None:
        raise BackupError(f"pg_dump timed out after {timed_out:.0f}s")
    if proc.returncode != 0:
        # Built from stderr only, which pg_dump writes without the DSN.
        raise BackupError(f"pg_dump failed: {proc.stderr[-500:]}")

    step("exporting the Master CV")
    from jobpilot.cv import store as cv_store
    from jobpilot.store.db import session_scope

    with session_scope() as db:
        cv_store.export_document(db, cv_out)

    step("verifying the files are not empty")
    # A backup job that reports success while writing a zero-byte file is worse
    # than no backup job at all, because it stops you checking.
    for path in (dump, cv_out):
        if not path.is_file() or path.stat().st_size == 0:
            raise BackupError(f"backup produced an empty file: {path.name}")

    mirrored = None
    if remote:
        step(f"uploading {(dump.stat().st_size + cv_out.stat().st_size) // 1024} KB to {remote}")
        if _mirror(dump, cv_out, remote, remote_keep_days, notes):
            mirrored = remote

    step("pruning old backups")
    pruned = _prune(directory, keep_days, keep_last)
    step(f"done — {len(pruned)} old file(s) removed" if pruned else "done — nothing to prune")

    return BackupResult(
        dump=dump,
        cv=cv_out,
        size=dump.stat().st_size + cv_out.stat().st_size,
        mirrored_to=mirrored,
        pruned=pruned,
        notes=notes,
    )


def backup_body(progress):
    """Task body for the queue, so the dashboard button and the CLI agree.

    Records a ``Run`` row like crawl and apply do. Tasks are evicted after the
    most recent fifty, so without this there is no way to answer "did last
    night's backup happen?" — which is the only question anyone asks about a
    backup until the day they need one.
    """
    from jobpilot.store.db import session_scope
    from jobpilot.store.models import Run
    from jobpilot.timeutil import vn_now

    with session_scope() as db:
        run = Run(kind="backup", started_at=vn_now(), stats={})
        db.add(run)
        db.commit()
        run_id = run.id

    try:
        result = run_backup(progress=progress)
    except Exception as exc:
        with session_scope() as db:
            row = db.get(Run, run_id)
            row.finished_at = vn_now()
            row.stats = {"ok": False, "error": str(exc)}
            db.commit()
        raise

    stats = {
        "ok": True,
        "dump": result.dump.name,
        "cv": result.cv.name,
        "size": result.size,
        "mirrored_to": result.mirrored_to,
        "pruned": len(result.pruned),
    }
    with session_scope() as db:
        row = db.get(Run, run_id)
        row.finished_at = vn_now()
        row.stats = stats
        db.commit()

    return {**stats, "pruned_names": result.pruned, "notes": result.notes}


def restore_hint(directory: Path | str | None = None) -> str:
    """The command that restores the newest dump, ready to paste.

    Present because a backup nobody knows how to restore is a backup nobody has.
    """
    files = [f for f in list_backups(directory) if f.kind == "database"]
    if not files:
        return ""
    directory = Path(directory or get_config().backup.dir).expanduser()
    newest = directory / files[0].name
    url = libpq_url(get_secrets().database_url)
    safe = re.sub(r"(://[^\s:/@]+:)([^\s@/]+)(@)", r"\1***\3", url)
    return f'pg_restore -d "{safe}" --clean "{newest}"'


